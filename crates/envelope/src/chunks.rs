use chacha20poly1305::{
    KeyInit, XChaCha20Poly1305, XNonce,
    aead::{Aead, Payload},
};

#[derive(Debug, PartialEq)]
pub enum ChunkError {
    AuthenticationFailed,
}

fn cipher_for(key: &[u8; 32]) -> XChaCha20Poly1305 {
    XChaCha20Poly1305::new_from_slice(key).expect("key is 32 bytes by type")
}

fn aead_encrypt(key: &[u8; 32], nonce: &[u8; 24], aad: &[u8], plaintext: &[u8]) -> Vec<u8> {
    let n: &XNonce = nonce.into();
    cipher_for(key)
        .encrypt(
            n,
            Payload {
                msg: plaintext,
                aad,
            },
        )
        .expect("payload length is within XChaCha20-Poly1305 limits")
}

fn aead_decrypt(
    key: &[u8; 32],
    nonce: &[u8; 24],
    aad: &[u8],
    ciphertext: &[u8],
) -> Result<Vec<u8>, ChunkError> {
    let n: &XNonce = nonce.into();
    cipher_for(key)
        .decrypt(
            n,
            Payload {
                msg: ciphertext,
                aad,
            },
        )
        .map_err(|_| ChunkError::AuthenticationFailed)
}

